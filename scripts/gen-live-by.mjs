// Builds api/_live-by.js from the hill app's own lesson lines (prototypes/greybox/lib/live-by.js), so the Guide server
// can turn the short ids the app sends ("buddhism/1:2", "light:0", question 3) back into fixed text it already knows.
// Nothing a user typed ever reaches the prompt this way. Rerun after editing lib/live-by.js:  node scripts/gen-live-by.mjs
import fs from "node:fs";
import vm from "node:vm";
const GB = new URL("../prototypes/greybox/", import.meta.url);
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(new URL("lib/live-by.js", GB), "utf8"), ctx);
const L = ctx.window.IH_LIVEBY;
const html = fs.readFileSync(new URL("hill-app-doors.html", GB), "utf8");
// the "my own religion" films: each film's single tradition, from the app's BF list
const bf = {};
for (const m of html.matchAll(/"((?:buddhism|christianity|catholic|judaism|islam|sikhism|hinduism|spiritual)\/\d+)": \{ t: (null|"[a-z]+")(?:, tag: "([^"]+)")?/g)) bf[m[1]] = m[3] || JSON.parse(m[2]);
const NAME = { buddhism: "Buddhism", christianity: "Christianity", catholic: "Catholicism", judaism: "Judaism", islam: "Islam", sikhism: "Sikhism", hinduism: "Hinduism" };
const films = {};
for (const [f, v] of Object.entries(L.films)) {
  const t = bf[f]; if (!t) throw new Error("no tradition for film " + f);
  films[f] = { t: NAME[t] || t, l: v.l.map((x) => [x[0], x[2] || ""]) };
}
// faith-path story lines: the story's own teaching, on its own path (d = the path's door, so a faith path only ever
// gets lines from its own stories)
const HOME_DOOR = { olive: "Christianity", angelus: "Catholicism", pomegranate: "Judaism", datepalm: "Islam", marigold: "Hinduism", lotus: "Buddhism", nectar: "Sikhism" };
const W = JSON.parse(html.match(/\(function \(W\) \{ HOMES\.forEach[^\n]*\}\)\((\{.*?\})\);/)[1]);
const homeOf = (id) => {
  const k = Object.keys(W).find((h) => W[h].includes(id));
  if (k) return k;
  try { return JSON.parse(fs.readFileSync(new URL(`lessons/${id}.json`, GB), "utf8")).home; } catch { return null; }
};
const paths = {};
for (const [id, v] of Object.entries(L.paths)) {
  const d = HOME_DOOR[homeOf(id)]; if (!d) throw new Error("no faith path for story " + id);
  paths[id] = { d, l: v.l.map((x) => [x[0], x[2] || v.src || ""]) };
}
const questions = L.questions.map((q) => q[0][0]);
const out = `// GENERATED by scripts/gen-live-by.mjs from prototypes/greybox/lib/live-by.js. Do not edit by hand.
// Fixed lesson lines the Guide can name when a person shares "what i live by" / "what spoke to you" (ids only).
export const LIVE_FILMS = Object.freeze(${JSON.stringify(films)});
export const LIVE_PATHS = Object.freeze(${JSON.stringify(paths)});
export const LIVE_QUESTIONS = Object.freeze(${JSON.stringify(questions)});
`;
fs.writeFileSync(new URL("../api/_live-by.js", import.meta.url), out);
console.log("films", Object.keys(films).length, "path stories", Object.keys(paths).length, "questions", questions.length);
